// Create repo + push ALL files in a single commit via the Git Data API.
// 6 API calls total regardless of file count (inline tree contents, no per-file blobs).
import { config } from '../config.js';

const API = 'https://api.github.com';

async function gh(method, path, body) {
  const res = await fetch(API + path, {
    method,
    headers: {
      Authorization: `Bearer ${config.github.token}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'User-Agent': 'yanga-core',
      ...(body ? { 'Content-Type': 'application/json' } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(30_000),
  });
  if (!res.ok) throw Object.assign(new Error(`github_${res.status}`), { code: `GITHUB_${res.status}` });
  return res.status === 204 ? null : res.json();
}

export async function createRepoWithFiles(repoName, description, files) {
  const org = config.github.org;
  // auto_init gives us an initial commit so the Git Data API works (empty repos return 409).
  const repo = await gh('POST', `/orgs/${org}/repos`, {
    name: repoName, description: description.slice(0, 300), private: true, auto_init: true,
    has_wiki: false, has_projects: false,
  });
  const branch = repo.default_branch || 'main';
  const ref = await gh('GET', `/repos/${org}/${repoName}/git/ref/heads/${branch}`);
  const parentSha = ref.object.sha;
  const parent = await gh('GET', `/repos/${org}/${repoName}/git/commits/${parentSha}`);

  const tree = await gh('POST', `/repos/${org}/${repoName}/git/trees`, {
    base_tree: parent.tree.sha,
    tree: files.map((f) => ({ path: f.path, mode: '100644', type: 'blob', content: f.content })),
  });
  const commit = await gh('POST', `/repos/${org}/${repoName}/git/commits`, {
    message: 'Initial app generated by Yanga.ai', tree: tree.sha, parents: [parentSha],
  });
  await gh('PATCH', `/repos/${org}/${repoName}/git/refs/heads/${branch}`, { sha: commit.sha });
  return { fullName: repo.full_name, url: repo.html_url, commitSha: commit.sha };
}
